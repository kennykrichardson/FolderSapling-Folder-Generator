import { ClipboardPaste, Sparkles } from 'lucide-react';

type Props = {
  value: string;
  onChange: (value: string) => void;
  onGenerate: () => void;
  error: string;
};

export default function StructureEditor({
  value,
  onChange,
  onGenerate,
  error,
}: Props) {
  return (
    <section className="panel editor-panel glass">
      <div className="panel-heading">
        <div>
          <span className="eyebrow">01 / INPUT</span>
          <h2>Your structure</h2>
        </div>
        <ClipboardPaste size={19} />
      </div>

      <p className="muted">
        Paste a folder tree generated by your favorite AI.
      </p>

      <textarea
        className="structure-input"
        value={value}
        onChange={(event) => onChange(event.target.value)}
        placeholder="Paste any folder structure from your preferred AI agent here..."
        spellCheck={false}
        aria-label="Project folder structure"
      />

      {error && <p className="error-message" role="alert">{error}</p>}

      <div className="sapling-button-frame sapling-button-frame--full">
        <button
          className="sapling-button"
          onClick={onGenerate}
          disabled={!value.trim()}
        >
          <Sparkles size={17} aria-hidden="true" />
          Grow my project
        </button>
      </div>
    </section>
  );
}
